"""Generates the Screen Cast icon set (Windows .ico + Android mipmaps).

The mark is intentionally simple: a dark rounded tile with a teal screen
outline and the two cast waves, so it stays readable at 16 px (taskbar/tray)
and at 192 px (launcher).

Run from the repository root with the bundled Python:

    python tool/generate_icons.py
"""

from __future__ import annotations

import os
import struct
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEAL = (53, 224, 161)
TOP = (12, 22, 30)
BOTTOM = (10, 34, 38)
ICON_SIZES = (256, 128, 64, 48, 32, 16)
ANDROID_DENSITIES = {
    "mipmap-mdpi": 48,
    "mipmap-hdpi": 72,
    "mipmap-xhdpi": 96,
    "mipmap-xxhdpi": 144,
    "mipmap-xxxhdpi": 192,
}


def _rounded_mask(size: int, radius_ratio: float = 0.22) -> Image.Image:
    mask = Image.new("L", (size, size), 0)
    draw = ImageDraw.Draw(mask)
    radius = int(size * radius_ratio)
    draw.rounded_rectangle((0, 0, size - 1, size - 1), radius=radius, fill=255)
    return mask


def _vertical_gradient(size: int) -> Image.Image:
    gradient = Image.new("RGB", (1, size))
    for y in range(size):
        t = y / max(1, size - 1)
        gradient.putpixel(
            (0, y),
            tuple(int(TOP[i] + (BOTTOM[i] - TOP[i]) * t) for i in range(3)),
        )
    return gradient.resize((size, size))


def render_icon(size: int) -> Image.Image:
    """Renders the mark at `size` px with supersampling for smooth edges."""
    ss = 4 if size <= 128 else 2
    canvas_size = size * ss
    image = Image.new("RGBA", (canvas_size, canvas_size), (0, 0, 0, 0))

    background = _vertical_gradient(canvas_size).convert("RGBA")
    image.paste(background, (0, 0), _rounded_mask(canvas_size))

    draw = ImageDraw.Draw(image)
    stroke = max(1, int(canvas_size * 0.05))
    left = int(canvas_size * 0.24)
    top = int(canvas_size * 0.17)
    right = int(canvas_size * 0.86)
    bottom = int(canvas_size * 0.55)
    draw.rounded_rectangle(
        (left, top, right, bottom),
        radius=int(canvas_size * 0.07),
        outline=TEAL,
        width=stroke,
    )

    # Cast waves: two quarter arcs in the lower-left, clear of the screen.
    origin = (int(canvas_size * 0.17), int(canvas_size * 0.86))
    wave_stroke = max(1, int(canvas_size * 0.045))
    for radius_ratio in (0.10, 0.18):
        radius = int(canvas_size * radius_ratio)
        draw.arc(
            (origin[0] - radius, origin[1] - radius,
             origin[0] + radius, origin[1] + radius),
            start=270,
            end=360,
            fill=TEAL,
            width=wave_stroke,
        )
    dot = int(canvas_size * 0.028)
    draw.ellipse(
        (origin[0] - dot, origin[1] - dot, origin[0] + dot, origin[1] + dot),
        fill=TEAL,
    )

    return image.resize((size, size), Image.LANCZOS)


def write_windows_icon() -> None:
    target = os.path.join(ROOT, "windows", "runner", "resources", "app_icon.ico")
    frames = [render_icon(size) for size in ICON_SIZES]
    frames[0].save(target, format="ICO", sizes=[(s, s) for s in ICON_SIZES])
    print(f"wrote {target} ({os.path.getsize(target)} bytes)")


def write_android_icons() -> None:
    res = os.path.join(ROOT, "android-app", "app", "src", "main", "res")
    for folder, size in ANDROID_DENSITIES.items():
        directory = os.path.join(res, folder)
        os.makedirs(directory, exist_ok=True)
        target = os.path.join(directory, "ic_launcher.png")
        render_icon(size).save(target, format="PNG")
        print(f"wrote {target}")


def write_foreground_vector() -> None:
    """Adaptive-icon foreground: the Material cast glyph, teal, in the safe zone."""
    res = os.path.join(ROOT, "android-app", "app", "src", "main", "res")
    target = os.path.join(res, "drawable", "ic_launcher_foreground.xml")
    glyph = (
        "M1,18h4c0,-1.66 -1.34,-3 -3,-3v3zM1,14v2c2.76,0 5,2.24 5,5h2c0,-3.87 "
        "-3.13,-7 -7,-7zM1,10v2c4.97,0 9,4.03 9,9h2c0,-6.08 -4.92,-11 -11,-11z"
        "M21,3H3c-1.1,0 -2,0.9 -2,2v3h2V5h18v14h-7v2h7c1.1,0 2,-0.9 2,-2V5c0,-1.1 "
        "-0.9,-2 -2,-2z"
    )
    content = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. The cast glyph sits inside the
     adaptive-icon safe zone (66 of 108 dp). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="24"
        android:translateY="24"
        android:scaleX="2.5"
        android:scaleY="2.5">
        <path
            android:fillColor="#35E0A1"
            android:pathData="{glyph}" />
    </group>
</vector>
"""
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    print(f"wrote {target}")


def main() -> None:
    write_windows_icon()
    write_android_icons()
    write_foreground_vector()


if __name__ == "__main__":
    main()
